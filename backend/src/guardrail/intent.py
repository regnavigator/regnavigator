"""의도 판정 — "이 질문에 법령 검색이 필요한가".

`should_search(text)`:
  1. 분류 서비스(INTENT_API_URL) 설정 시 → 4분류 후 규제군(법령문의/업무절차)만 검색.
  2. 미설정 시 → 인사말·감사 등 명백한 off-topic 만 제외하고 나머지는 검색(안전
     기본값 = 근거 우선). 규제 챗봇은 대부분 질의가 규제라 이 폴백으로도 충분.

이 판정으로 검색을 결정적으로 강제(`IntentSearchMiddleware`)해, 답변 모델이
검색을 건너뛰고 환각하는 것을 원천 차단한다.
"""

from __future__ import annotations

import re

from src.guardrail import intent_client

# 전체 메시지가 이것뿐이면 off-topic(검색 불필요) — 인사·감사·수락 등.
_OFFTOPIC = {
    "안녕", "안녕하세요", "안녕하십니까", "반가워", "반갑습니다", "하이", "하잉",
    "ㅎㅇ", "hi", "hello", "헬로", "헬루", "방가", "방갑", "안뇽", "하위",
    "굿모닝", "굿애프터눈", "굿이브닝", "굿밤", "좋은아침", "좋은하루",
    "고마워", "고마워요", "고맙습니다", "감사", "감사해요", "감사합니다",
    "ㄳ", "ㄱㅅ", "땡큐", "쌩큐", "수고", "수고하세요", "수고했어", "잘가", "바이",
    "ok", "오케이", "넵", "네", "응", "좋아", "좋아요", "알겠어",
    "알겠습니다", "확인", "굿", "ㅇㅇ", "ㅇㅋ",
}

# 전체 메시지가 이것뿐이면 실질 물음이 없는 발화(=검색 강제 안 함) — 재촉·필러.
# 강제 검색을 풀면 답변 모델이 직전 맥락에 진짜 규제 질문이 있을 때만 스스로
# 검색하고, 없으면 되묻는다(주제 날조 차단 — supervisor 프롬프트 C 분기와 짝).
_NO_QUESTION = {
    "대답", "대답해", "대답해줘", "대답하라고", "대답좀", "답", "답해", "답해줘",
    "답변", "답변해", "답변해줘", "말해", "말해봐", "말해줘",
    "빨리", "빨리해", "어서", "계속", "계속해", "그래서", "그리고",
    "다시", "다시해", "재답변", "재검색", "리트라이", "해줘", "해봐", "ㄱㄱ",
}


# 서비스 자체·현재 시점을 묻는 메타 질문("너 누구야"·"지금 몇시야")은 **분류기가
# 담당**한다 — 여기에 정규식 레이어를 두지 않는다. 실측(2026-07-25, 라이브 0.8B):
# 메타 10건 중 9건 정확, 정규식이 놓친 "넌 뭐하는 애야"까지 맞혔다. 유일한 누락
# ("현재 시각 알려줘")은 serve_intent.py few-shot 에 예시를 추가해 분류기 쪽에서
# 고쳤다. 판정 레이어를 하나로 유지 = 이 파일과 분류기가 갈라지지 않는다.
#
# ⚠️ **인사만은 예외 — 로컬에서 차단한다**(2026-08-01 사용자 지적: "ㅎㅇ만 해도
# tavily·vector 검색이 되면 어떡함, 그 전에 차단해야지"). 분류기에 맡길 수 없는
# 이유가 구조적이다: 분류기 시스템 프롬프트가 "**직전 대화가 규제 주제면 이어지는
# 후속 질문도 '예'**" 라고 지시하므로, 규제 대화 도중의 인사에도 '예'를 답한다
# (실측: 맥락 있을 때 'ㅎㅇ요'·'굿모닝'·'ㅎㅇㅎㅇ' → 검색 강제). 분류기가 죽으면
# 폴백이 '검색'이라 더 새고. 순수 인사는 **답할 내용 자체가 없어 차단해도 환각
# 위험이 0** 이므로 로컬 차단이 안전하다(메타 질문과 다른 점).
_HONORIFIC_SUFFIXES = (
    "하셨습니다", "하셨어요", "했습니다", "했어요", "하세요", "드립니다", "드려요",
    "입니다", "습니다", "니다", "해요", "예요", "요", "용",
)


def _variants(core: str) -> tuple[str, ...]:
    """인사 변형 흡수 — 목록 나열만으로는 계속 새므로 형태를 정규화한다.

    ① 원형 ② 반복 축약("ㅎㅇㅎㅇ"→"ㅎㅇ", "안녕안녕"→"안녕")
    ③ 존칭·어미 절단("ㅎㅇ요"→"ㅎㅇ", "하이요"→"하이")
    ②③ 조합까지 본다. 전체 메시지가 인사일 때만 매칭되므로
    "안녕하세요 의료기기 허가는?" 같은 진짜 질문은 걸리지 않는다.
    """
    out = {core}
    for v in (core, re.sub(r"^(.+?)\1+$", r"\1", core)):
        out.add(v)
        # 존칭·경어 어미 절단 — "수고하셨습니다"→"수고", "하이요"→"하이".
        # ⚠️ 하나의 정규식 alternation 으로 묶으면 더 앞에서 매칭된 대안이
        #    선점한다("하이요" 가 '이요' 에 걸려 '하' 가 됨) → **접미사마다
        #    독립 절단해 후보를 전부 만든다**.
        for suf in _HONORIFIC_SUFFIXES:
            if v.endswith(suf) and len(v) > len(suf):
                out.add(v[: -len(suf)])
    return tuple(x for x in out if x)


def _looks_offtopic(text: str) -> bool:
    """메시지 전체가 인사말/짧은 수락/물음없는 재촉인지(=검색 강제 불필요).

    **정확 일치만** — "좋아 그럼 처벌은?" 처럼 인사말로 시작하지만 규제 질문이
    이어지는 경우를 off-topic 으로 오판하지 않도록, 정리된 전체가 인사말/재촉
    하나와 같을 때만 스킵(그 외엔 검색 = 근거 우선). 문맥 판단은 분류기가.

    웃음 정규화: 끝에 붙은 ㅋㅋ/ㅎㅎ만 제거("안녕ㅋㅋ"→"안녕"). 선두 ㅎ("ㅎㅇ"=하이)은
    보존해야 하므로 전역 strip 금지 — 과거엔 ㅎ 전역 제거로 "ㅎㅇ"이 "ㅇ"이 돼
    인사 인식이 깨졌다(2026-07-21 3턴 라우팅 버그 turn 1).
    """
    t = re.sub(r"[\s!?.,~^]+", "", (text or "").strip()).lower()
    if not t:
        return True
    if set(t) <= {"ㅋ", "ㅎ", "ㅠ", "ㅜ"}:   # 순수 웃음·울음
        return True
    core = re.sub(r"[ㅋㅎ]+$", "", t) or t   # 말미 웃음만 제거
    return any(v in _OFFTOPIC or v in _NO_QUESTION for v in _variants(core))


def should_search(text: str, context: str | None = None) -> bool:
    """규제 검색 필요 여부.

    1. 정확 인사말/물음없는 재촉 → False (분류기 호출 없이 스킵 — 안녕/대답해).
    2. 그 외 → 분류기(context 반영) 판정. 분류기 미설정/실패 → True(안전 기본값).
       메타 질문("너 누구야"·"지금 몇시야")도 여기서 분류기가 '아니오'로 거른다.
    """
    if _looks_offtopic(text):
        return False
    sn = intent_client.classify(text, context)
    return True if sn is None else sn
